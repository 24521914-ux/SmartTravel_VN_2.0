"""Standard compose layout: app-only docker-compose.yml + local docker-compose.local.yml.

Renders with the Docker Compose CLI (no daemon needed). Also keeps the P03 isolated stack,
still generated by p02.configuration(), equivalent to the local stack, and tests init_env.py.
"""
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest import mock

import p02

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'backend/platform'))
import init_env  # noqa: E402

SERVICES = p02.SERVICES
BASE = ROOT / 'docker-compose.yml'
OVERRIDE = ROOT / 'docker-compose.local.yml'
LOCAL_ONLY = {*(s + '-db' for s in SERVICES), 'community-keygen', 'mongo-init', 'identity-mail',
              'source-sandbox', 'sandbox-init'}
# Settings the static stack states explicitly where the generated P03 stack relies on defaults.
EXTRA_SETTINGS = {
    'identity': {'WORKLOAD_TOKEN_URI', 'IDENTITY_MAIL_FROM', 'MAIL_USERNAME', 'MAIL_PASSWORD',
                 'MAIL_AUTH', 'MAIL_TLS_REQUIRED', 'MAIL_TIMEOUT_MS'},
    'gateway': {'AI_ENABLED', 'GATEWAY_RESPONSE_TIMEOUT'},
}


def render(env_file, *files):
    arguments = [arg for path in files for arg in ('-f', str(path))]
    result = subprocess.run(['docker', 'compose', '--env-file', str(env_file), *arguments, 'config', '--format', 'json'],
                            check=True, capture_output=True, text=True, encoding='utf-8', cwd=ROOT)
    return json.loads(result.stdout)


class ComposeLayoutTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.folder = tempfile.TemporaryDirectory()
        cls.env_file = Path(cls.folder.name) / '.env'
        init_env.prepare(cls.env_file, 'local', ROOT / '.env.local.example')
        cls.values = init_env.read_env(cls.env_file)
        cls.base = render(cls.env_file, BASE)
        cls.local = render(cls.env_file, BASE, OVERRIDE)
        with tempfile.TemporaryDirectory() as folder, mock.patch.object(p02, 'LOCAL', Path(folder)):
            p02.configuration(cls.values)
            import yaml
            cls.generated = yaml.safe_load((Path(folder) / 'compose.yaml').read_text(encoding='utf-8'))

    @classmethod
    def tearDownClass(cls):
        cls.folder.cleanup()

    def test_base_runs_only_gateway_services_broker_and_init_jobs(self):
        services = self.base['services']
        self.assertEqual(set(services), {'gateway', 'rabbitmq', 'rabbit-init', 'key-init', 'community-migrate', *SERVICES})
        for name, spec in services.items():
            if name != 'gateway':
                self.assertFalse(spec.get('ports'), name)
            self.assertFalse(set(spec.get('depends_on', {})) & LOCAL_ONLY, name)
        self.assertEqual(services['gateway']['ports'][0]['host_ip'], '127.0.0.1')
        self.assertEqual(int(services['gateway']['ports'][0]['published']), 58080)
        for service in SERVICES:
            self.assertEqual(services[service]['depends_on']['rabbit-init']['condition'], 'service_completed_successfully')
            self.assertIn('healthcheck', services[service], service)
        self.assertEqual(services['identity']['depends_on']['key-init']['condition'], 'service_completed_successfully')
        self.assertEqual(services['community']['depends_on']['community-migrate']['condition'], 'service_completed_successfully')

    def test_override_adds_only_local_dependencies_and_loopback_ports(self):
        services = self.local['services']
        self.assertEqual(set(services) - set(self.base['services']), LOCAL_ONLY)
        for name, spec in services.items():
            self.assertTrue(all(p['host_ip'] == '127.0.0.1' for p in spec.get('ports', [])), name)
        for name in (s + '-db' for s in SERVICES):
            self.assertFalse(services[name].get('ports'), name)
        for service in p02.PORTS:
            self.assertEqual(int(services[service]['ports'][0]['published']), p02.PORTS[service], service)
        for service in init_env.POSTGRES_SERVICES:
            self.assertEqual(services[service]['depends_on'][service + '-db']['condition'], 'service_healthy')
        self.assertEqual(services['community-migrate']['depends_on']['mongo-init']['condition'], 'service_completed_successfully')
        self.assertEqual(services['gateway']['depends_on']['sandbox-init']['condition'], 'service_completed_successfully')
        self.assertEqual(set(services['sandbox-init']['depends_on']), {'catalog'})
        self.assertEqual(services['sandbox-init']['depends_on']['catalog']['condition'], 'service_healthy')

    def test_existing_volumes_keep_their_names(self):
        volumes = self.local['volumes']
        for name in ['identity-data', 'catalog-data', 'trip-data', 'ingestion-data', 'intelligence-data',
                     'community-data', 'community-key', 'identity-signing-keys', *(s + '-objects' for s in SERVICES)]:
            self.assertEqual(volumes[name]['name'], 'smarttravel-p02_' + name, name)

    def test_every_required_variable_comes_from_the_example(self):
        text = BASE.read_text(encoding='utf-8') + OVERRIDE.read_text(encoding='utf-8')
        import re
        required = set(re.findall(r'\$\{([A-Z0-9_]+):\?', text))
        example = init_env.read_env(ROOT / '.env.local.example')
        self.assertEqual(required - set(example), set())

    def test_local_stack_matches_generated_p03_stack(self):
        for name in [*SERVICES, 'gateway']:
            static = dict(self.local['services'][name]['environment'])
            generated = dict(self.generated['services'][name]['environment'])
            if 'SPRING_APPLICATION_JSON' in generated:
                self.assertEqual(json.loads(static.pop('SPRING_APPLICATION_JSON')),
                                 json.loads(generated.pop('SPRING_APPLICATION_JSON')), name)
            # The broker service is named rabbitmq here; P03 keeps the P01 name.
            if 'BROKER_HOST' in generated:
                self.assertEqual((static.pop('BROKER_HOST'), generated.pop('BROKER_HOST')), ('rabbitmq', 'identity-broker'))
            extra = EXTRA_SETTINGS.get(name, set())
            self.assertEqual({k: v for k, v in static.items() if k not in extra}, generated, name)
            self.assertEqual(self.local['services'][name]['image'], self.generated['services'][name]['image'], name)


class InitEnvTests(unittest.TestCase):
    def test_default_prepare_uses_cloud_template_and_keeps_database_settings(self):
        with tempfile.TemporaryDirectory() as folder:
            env_file = Path(folder) / '.env'
            written = init_env.prepare(env_file)
            values = init_env.read_env(env_file)
            example = init_env.read_env(ROOT / '.env.example')
            self.assertEqual(set(written), set(init_env.INTERNAL_SECRETS))
            for key in init_env.DATABASE_SETTINGS & example.keys():
                self.assertEqual(values[key], example[key], key)
            before = env_file.read_bytes()
            self.assertEqual(init_env.prepare(env_file), [])
            self.assertEqual(env_file.read_bytes(), before)

    def test_cli_defaults_to_cloud_env(self):
        with mock.patch.object(sys, 'argv', ['init_env.py']), \
             mock.patch.object(init_env, 'prepare', return_value=[]) as prepare, \
             mock.patch.object(init_env, 'read_env', return_value={}), \
             mock.patch('builtins.print'):
            self.assertEqual(init_env.main(), 0)
        prepare.assert_called_once_with((ROOT / '.env').resolve(), 'cloud')

    def test_local_mode_generates_secrets_and_local_connections(self):
        with tempfile.TemporaryDirectory() as folder:
            env_file = Path(folder) / '.env'
            written = init_env.prepare(env_file, 'local', ROOT / '.env.local.example')
            values = init_env.read_env(env_file)
            self.assertFalse([n for n, v in values.items() if v == init_env.PLACEHOLDER])
            self.assertTrue(set(init_env.INTERNAL_SECRETS) | set(init_env.LOCAL_DATABASE_SECRETS) <= set(written))
            self.assertEqual(values['CATALOG_DB_URL'], 'jdbc:postgresql://catalog-db:5432/catalog_db')
            self.assertIn(values['COMMUNITY_RUNTIME_PASSWORD'] + '@community-db:27017/community_db', values['COMMUNITY_MONGODB_URI'])
            self.assertTrue(values['COMMUNITY_MONGODB_MIGRATION_URI'].startswith('mongodb://community_migrator:'))
            before = env_file.read_text(encoding='utf-8')
            self.assertEqual(init_env.prepare(env_file, 'local', ROOT / '.env.local.example'), [])
            self.assertEqual(env_file.read_text(encoding='utf-8'), before)

    def test_existing_env_is_completed_without_rotating_values(self):
        with tempfile.TemporaryDirectory() as folder:
            env_file = Path(folder) / '.env'
            env_file.write_text('# old file\nAI_ENABLED=true\nCOMMUNITY_RUNTIME_PASSWORD=keep/me+1\n'
                                'BROKER_ADMIN_PASSWORD=keep-broker\n', encoding='utf-8')
            written = init_env.prepare(env_file, 'local', ROOT / '.env.local.example')
            values = init_env.read_env(env_file)
            self.assertEqual(values['BROKER_ADMIN_PASSWORD'], 'keep-broker')
            self.assertEqual(values['AI_ENABLED'], 'true')
            self.assertNotIn('COMMUNITY_RUNTIME_PASSWORD', written)
            # Passwords are URL-encoded inside the derived URI.
            self.assertIn('community_runtime:keep%2Fme%2B1@', values['COMMUNITY_MONGODB_URI'])
            self.assertIn('IDENTITY_DB_URL', written)

    def test_cloud_mode_never_writes_database_settings(self):
        with tempfile.TemporaryDirectory() as folder:
            env_file = Path(folder) / '.env.cloud'
            written = init_env.prepare(env_file, 'cloud')
            self.assertFalse(set(written) & init_env.DATABASE_SETTINGS)
            self.assertIn('YOUR_TRIP_HOST', init_env.read_env(env_file)['TRIP_DB_URL'])

    def test_real_env_files_are_ignored(self):
        for name in ('.env', '.env.local', '.env.cloud'):
            self.assertEqual(subprocess.run(['git', 'check-ignore', '-q', name], cwd=ROOT).returncode, 0, name)


class ComposeSelectionTests(unittest.TestCase):
    def test_default_compose_has_only_cloud_base(self):
        with mock.patch.dict(os.environ, {}, clear=True), \
             mock.patch.object(p02, 'prepare', return_value={}), \
             mock.patch.object(p02, 'run') as run:
            p02.compose('config')
        command = run.call_args.args[0]
        self.assertEqual(command, ['docker', 'compose', '--env-file', str(p02.ENV_FILE),
                                   '-f', str(BASE), 'config'])

    def test_ci_explicit_local_selection_is_respected(self):
        settings = {'COMPOSE_FILE': 'docker-compose.yml:docker-compose.local.yml',
                    'COMPOSE_PATH_SEPARATOR': ':', 'P02_ENV_FILE': '.env.local',
                    'COMPOSE_ENV_FILES': '.env.local'}
        with mock.patch.dict(os.environ, settings, clear=True), \
             mock.patch.object(p02, 'ENV_FILE', ROOT / '.env.local'), \
             mock.patch.object(p02, 'prepare', return_value={}), \
             mock.patch.object(p02, 'run') as run:
            p02.compose('config')
        self.assertEqual(run.call_args.args[0], ['docker', 'compose', '--env-file', str(ROOT / '.env.local'),
                                                '-f', str(BASE), '-f', str(OVERRIDE), 'config'])

    def test_db_ports_cannot_add_local_databases_to_cloud(self):
        with mock.patch.dict(os.environ, {'P02_DB_PORTS': '1'}, clear=True), \
             mock.patch.object(p02, 'prepare', return_value={}), \
             mock.patch.object(p02, 'run') as run:
            with self.assertRaises(ValueError):
                p02.compose('up', '-d')
        run.assert_not_called()


if __name__ == '__main__':
    unittest.main()
